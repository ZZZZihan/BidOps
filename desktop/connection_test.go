func TestEndpointRejectsRemoteOrAmbiguousTargets(t *testing.T) {
	for _, raw := range []string{
		"https://127.0.0.1:8765/", "http://localhost:8765/", "http://0.0.0.0:8765/",
		"http://[::1]:8765/", "http://example.com:8765/", "http://127.0.0.1/",
		"http://127.0.0.1:0/", "http://127.0.0.1:65536/", "http://127.0.0.1:abc/",
		"http://user:password@127.0.0.1:8765/", "http://127.0.0.1:8765/api",
		"http://127.0.0.1:8765/?", "http://127.0.0.1:8765/#", "http://127.0.0.1:8765/?key=value",
		"http://127.0.0.1:8765/#state", "http://127.0.0.1:8765/%2F", "//127.0.0.1:8765/",
	} {
		t.Run(raw, func(t *testing.T) {
			if _, err := parseEndpoint(raw); err == nil {
				t.Fatal("accepted a target outside the explicit loopback root")
			}
		})
	}
	for _, raw := range []string{defaultServiceURL, "http://127.0.0.1:23456"} {
		if _, err := parseEndpoint(raw); err != nil {
			t.Fatalf("valid target %s: %v", raw, err)
		}
	}
}

func TestNavigationKeepsLoginAndAPIsOnTheConfiguredOrigin(t *testing.T) {
	endpoint, _ := parseEndpoint(defaultServiceURL)
	for _, raw := range []string{
		defaultServiceURL, "http://127.0.0.1:8765/api/auth/login",
		"http://127.0.0.1:8765/api/auth/callback?code=fixture&state=fixture",
	} {
		if !endpoint.sameOrigin(raw) {
			t.Errorf("blocked local navigation: %s", raw)
		}
	}
	for _, raw := range []string{
		"https://127.0.0.1:8765/", "http://127.0.0.1:8766/", "http://localhost:8765/",
		"http://127.0.0.1:8765.evil.test/", "http://user@127.0.0.1:8765/", "javascript:alert(1)",
	} {
		if endpoint.sameOrigin(raw) {
			t.Errorf("allowed an origin change: %s", raw)
		}
	}
	for _, raw := range []string{"mygo://localhost/", "http://mygo.localhost/index.html"} {
		if !isOfflineURL(raw) {
			t.Errorf("blocked built-in page: %s", raw)
		}
	}
	for _, raw := range []string{"file:///tmp/test.html", "mygo://other/", "http://mygo.localhost:12/"} {
		if isOfflineURL(raw) {
			t.Errorf("allowed non-app page as built-in content: %s", raw)
		}
	}
}

