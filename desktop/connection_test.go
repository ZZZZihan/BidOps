func TestProbeOnlyReadsRootWithoutCookiesOrProxy(t *testing.T) {
	var requests atomic.Int32
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		requests.Add(1)
		if r.Method != http.MethodGet || r.URL.RequestURI() != "/" || r.Header.Get("Cookie") != "" || r.Header.Get("Authorization") != "" {
			t.Errorf("unexpected request: %s %s; credentials present: %t", r.Method, r.URL.RequestURI(), r.Header.Get("Cookie") != "" || r.Header.Get("Authorization") != "")
		}
		w.Header().Set("Content-Type", "text/html; charset=utf-8")
		w.Header().Set("Set-Cookie", "fixture=private; HttpOnly")
		_, _ = w.Write([]byte("<!doctype html><title>BidOps · 采购证据工作台</title><main>fixture</main>"))
	}))
	defer server.Close()
	endpoint, err := parseEndpoint(server.URL)
	if err != nil {
		t.Fatal(err)
	}
	client := probeClient()
	if client.Jar != nil || client.Transport.(*http.Transport).Proxy != nil {
		t.Fatal("connection probe must not inherit browser cookies or environment proxy")
	}
	for range 2 {
		if err := probeService(context.Background(), client, endpoint); err != nil {
			t.Fatal(err)
		}
	}
	if requests.Load() != 2 {
		t.Fatalf("made %d requests, want exactly two explicit root GETs", requests.Load())
	}
}

func TestProbeRejectsBadStatusUnrelatedPagesAndRedirects(t *testing.T) {
	var redirected atomic.Bool
	redirectTarget := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		redirected.Store(true)
		w.WriteHeader(http.StatusOK)
	}))
	defer redirectTarget.Close()
	for _, tc := range []struct {
		name        string
		status      int
		contentType string
		body        string
		redirect    bool
	}{
		{"backend_error", 503, "text/html", "<title>BidOps</title>", false},
		{"missing_frontend", 404, "application/json", `{}`, false},
		{"not_html", 200, "application/json", `{"title":"BidOps"}`, false},
		{"wrong_service", 200, "text/html", "<title>Different application</title>", false},
		{"missing_title", 200, "text/html", "<main>BidOps</main>", false},
		{"redirect", 302, "text/html", "", true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				w.Header().Set("Content-Type", tc.contentType)
				if tc.redirect {
					w.Header().Set("Location", redirectTarget.URL)
				}
				w.WriteHeader(tc.status)
				_, _ = w.Write([]byte(tc.body))
			}))
			defer server.Close()
			endpoint, _ := parseEndpoint(server.URL)
			if err := probeService(context.Background(), probeClient(), endpoint); err == nil {
				t.Fatal("probe accepted an unusable or unrelated service")
			}
		})
	}
	if redirected.Load() {
		t.Fatal("probe followed a redirect")
	}
}

func TestProbeTimeoutAndRecoveryUseExplicitAttempts(t *testing.T) {
	var unavailable atomic.Bool
	unavailable.Store(true)
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if unavailable.Load() {
			<-r.Context().Done()
			return
		}
		w.Header().Set("Content-Type", "text/html")
		_, _ = w.Write([]byte("<title>BidOps fixture</title>"))
	}))
	defer server.Close()
	endpoint, _ := parseEndpoint(server.URL)
	client := probeClient()
	client.Timeout = 40 * time.Millisecond
	if err := probeService(context.Background(), client, endpoint); err == nil {
		t.Fatal("unavailable service did not time out")
	}
	unavailable.Store(false)
	if err := probeService(context.Background(), client, endpoint); err != nil {
		t.Fatalf("explicit retry failed after recovery: %v", err)
	}
	server.Close()
	if err := probeService(context.Background(), client, endpoint); err == nil {
		t.Fatal("closed listener was accepted")
	}
}
