func TestLoadFailureRecoversMissingURLWithoutLoopingOfflinePage(t *testing.T) {
	endpoint, _ := parseEndpoint(defaultServiceURL)
	for _, tc := range []struct {
		name, failedURL, currentURL string
		loading, want               bool
	}{
		{"known_failed_service", defaultServiceURL, "mygo://localhost/", false, true},
		{"missing_native_url_after_navigation", "", defaultServiceURL, false, true},
		{"missing_native_url_during_initial_load", "", "mygo://localhost/", true, true},
		{"offline_failure_must_not_loop", "", "mygo://localhost/", false, false},
		{"explicit_other_origin", "https://example.org/", defaultServiceURL, false, false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if got := endpoint.recoverableLoadFailure(tc.failedURL, tc.currentURL, tc.loading); got != tc.want {
				t.Fatalf("recovery=%v, want %v", got, tc.want)
			}
		})
	}
}

